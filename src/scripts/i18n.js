export function currentLanguage() {
  return document.documentElement.lang === 'en' ? 'en' : 'ar';
}

export function t(key, language = currentLanguage()) {
  return copy[key]?.[language] ?? key;
}

function applyTranslations(language) {
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const suffix = element.dataset.i18nSuffix;
    element.textContent = `${t(element.dataset.i18n, language)}${suffix ? ` ${suffix}` : ''}`;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    element.innerHTML = t(element.dataset.i18nHtml, language);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAria, language));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', t(element.dataset.i18nAlt, language));
  });
  document.querySelectorAll('[data-i18n-dir]').forEach((element) => {
    element.setAttribute('dir', language === 'ar' ? 'rtl' : 'ltr');
  });

  try { localStorage.setItem('ta_ui_language', language); } catch (_) {}
  try { sessionStorage.setItem('ta_ui_language', language); } catch (_) {}
  document.dispatchEvent(new CustomEvent('ta-language-changed', { detail: { language } }));
}

export function setLanguage(language) {
  applyTranslations(language === 'en' ? 'en' : 'ar');
}

export function initI18n() {
  let language = 'ar';
  try { language = localStorage.getItem('ta_ui_language') || language; } catch (_) {}
  if (language !== 'en' && language !== 'ar') language = 'ar';
  applyTranslations(language);
  window.setLanguage = setLanguage;
  window.toggleLanguage = () => setLanguage(currentLanguage() === 'ar' ? 'en' : 'ar');
}

